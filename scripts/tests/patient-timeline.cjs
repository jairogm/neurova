const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const moduleExports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/patient-timeline.ts', 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText, {exports: moduleExports, Date, Intl});
const {buildPatientTimeline: build, timelineDate} = moduleExports;
const patient = {created_at: '2026-01-01T10:00:00Z'};
const session = {_id: 's1', scheduled_date: '2026-11-05T10:00:00Z', created_at: '2026-10-01T10:00:00Z', payment_status: 'paid', payment_amount: 100000};
const events = build(patient, [{_id: 'n1', title: 'Note', date: '2026-11-04', created_at: '2026-11-03'}, {_id: 'deleted', created_at: '2026-11-06', deleted_at: 1}], [session, {...session, _id: 'cancelled', session_status: 'cancelled', payment_status: 'unpaid'}], [{_id: 'd1', kind: 'consent', name: 'consent.pdf', uploaded_at: '2026-11-06T10:00:00Z'}]);
assert.equal(events[0].title, 'Consent form uploaded');
assert.equal(events[0].tab, 'documents');
assert.ok(events.some(e => e.title.includes('Scheduled')));
assert.ok(events.some(e => e.title.includes('Cancelled')));
assert.equal(events.filter(e => e.type === 'payment').length, 1);
assert.ok(events.find(e => e.type === 'payment').description.includes('Shown on session date'));
assert.equal(events.at(-1).title, 'Patient added');
assert.equal(events.some(e => e.key.includes('deleted')), false);
assert.equal(events.some(e => /Card on file|Intake completed/.test(e.title + e.description)), false);
assert.equal(timelineDate('2026-11-04').getDate(), 4);
assert.equal(timelineDate('bad-date'), null);
const invalid = build(patient, [{_id: 'invalid', date: 'invalid', created_at: '2026-11-02'}], [], []);
assert.equal(invalid[0].date, '2026-11-02');
assert.equal(build(patient, Array.from({length: 15}, (_, i) => ({_id: String(i), created_at: '2026-11-01'})), [], []).length, 16);
console.log('13 timeline checks passed');
