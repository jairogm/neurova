const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('NEUROVA.dc.html', 'utf8').match(/<script type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/)[1];
class DCLogic {
 constructor(props) { this.props = props; }
 setState(update) { this.state = {...this.state, ...(typeof update === 'function' ? update(this.state) : update)}; }
}
let revoked = false;
const Demo = vm.runInNewContext(source + '\nComponent;', {DCLogic, React: {createElement: () => null}, Date, URL: {createObjectURL: () => 'blob:sample', revokeObjectURL: () => {revoked = true;}}, window: {open: () => {}}});
const demo = new Demo({});
assert.ok(demo.renderVals().patientTabs.some(t => t.label === 'Documents' || JSON.stringify(t).includes('Documents')));
assert.equal(demo.renderVals().consentLabel, 'Consent form missing');
let reset = false;
demo.state.documentFile = {name: 'sample.pdf', type: 'application/pdf', size: 300};
demo.renderVals().uploadDocument({preventDefault() {}, target: {reset() {reset = true;}}});
assert.equal(reset, true);
assert.equal(demo.renderVals().documents.length, 1);
assert.equal(demo.renderVals().consentLabel, 'Consent form uploaded');
assert.ok(demo.renderVals().timeline.some(e => e.title === 'Consent form uploaded'));
demo.state.selectedPatientId = 'david';
assert.equal(demo.renderVals().documents.length, 0);
assert.equal(demo.renderVals().sessions.length, 1);
assert.equal(demo.renderVals().sessions[0].statusLabel, 'Scheduled');
demo.state.selectedPatientId = 'maya';
demo.renderVals().documents[0].askDelete();
assert.equal(demo.renderVals().confirmTitle, 'Delete document?');
demo.renderVals().closeConfirm();
assert.equal(demo.renderVals().documents.length, 1);
demo.renderVals().documents[0].askDelete();
demo.renderVals().doConfirm();
assert.equal(revoked, true);
assert.equal(demo.renderVals().documents.length, 0);
assert.equal(demo.renderVals().consentLabel, 'Consent form missing');
assert.equal(demo.renderVals().timeline.some(e => e.title === 'Consent form uploaded'), false);
demo.state.documentFile = {name: 'bad.html', type: 'text/html', size: 300};
demo.renderVals().uploadDocument({preventDefault() {}});
assert.equal(demo.state.documents.length, 0);
assert.ok(demo.state.documentMessage.includes('PDF'));
demo.state.timelineFilter = 'payment';
assert.ok(demo.renderVals().timeline.every(e => e.type === 'payment'));
// Payment changes update only the selected session and the timeline.
const row = demo.renderVals().sessions[0];
row.setPayment({target: {value: 'Waived'}});
assert.equal(demo.renderVals().sessions[0].pay, 'Waived');
row.setPayment({target: {value: 'Paid'}});
assert.equal(demo.renderVals().sessions[0].pay, 'Paid');
assert.ok(demo.renderVals().sessions[0].amt.includes('120.000'));
// A real demo appointment is created and appears in the calendar and patient.
demo.state.timelineFilter = 'all';
demo.state.scheduleDraft = {patientId: 'david', date: new Date().toLocaleDateString('en-CA'), time: '15:00', duration: '60', amount: '150000', notes: 'Sample'};
const before = demo.state.sessions.length;
demo.renderVals().submitSchedule({preventDefault() {}});
assert.equal(demo.state.sessions.length, before + 1);
assert.equal(demo.state.selectedPatientId, 'david');
assert.equal(demo.state.patientTab, 'sessions');
assert.ok(demo.renderVals().sessions.some(s => s.dur === '60 min' && s.amt.includes('150.000')));
demo.state.view = 'schedule';
assert.ok(demo.renderVals().agenda.some(a => a.patient.id === 'david' && a.dur === '60 min'));
assert.equal(demo.renderVals().weekTotal, 6);
// Day selection works and medical history is isolated by patient.
demo.renderVals().weekDays.find(d => d.countLabel === '—').select();
assert.equal(demo.renderVals().agenda.length, 0);
demo.state.selectedPatientId = 'david';
demo.renderVals().history[0].change({target: {value: 'Sample expectation'}});
assert.equal(demo.renderVals().history[0].val, 'Sample expectation');
demo.state.selectedPatientId = 'maya';
assert.notEqual(demo.renderVals().history[0].val, 'Sample expectation');
demo.state.schedRecur = 'weekly';
const recurringBefore = demo.state.sessions.length;
demo.renderVals().submitSchedule({preventDefault() {}});
assert.equal(demo.state.sessions.length, recurringBefore + 4);
assert.equal(new Date(demo.state.sessions[1].date).getTime() - new Date(demo.state.sessions[0].date).getTime(), 7 * 86400000);
demo.state.scheduleDraft.duration = '0';
const invalidBefore = demo.state.sessions.length;
demo.renderVals().submitSchedule({preventDefault() {}});
assert.equal(demo.state.sessions.length, invalidBefore);
assert.ok(demo.state.scheduleError);
assert.ok(demo.renderVals().stats[1].value);
console.log('36 demo interaction checks passed');
